# Comptes de tiers que l'on rapproche (lettrage) : fournisseurs, clients,
# personnel, associés, débiteurs/créditeurs divers, créances/dettes HAO.
PREFIXES_LETTRABLES = ("40", "41", "42", "46", "47", "48")


def classe_de(numero: str) -> int:
    """Classe d'un compte (premier chiffre)."""
    if not numero or not numero[0].isdigit():
        raise ValueError(f"Numéro de compte invalide : {numero!r}.")
    return int(numero[0])


def est_lettrable_par_defaut(numero: str) -> bool:
    return numero.startswith(PREFIXES_LETTRABLES) and len(numero) >= 3


def est_imputable_par_defaut(numero: str) -> bool:
    """Classes et rubriques (1 et 2 chiffres) ne reçoivent pas d'écritures."""
    return len(numero) >= 3


def libelle_standard(numero: str) -> str | None:
    """Libellé du référentiel pour un numéro, s'il existe."""
    return _INDEX.get(numero)


_INDEX: dict[str, str] = dict(PLAN_SYSCOHADA)


def _controler_referentiel() -> None:
    """Contrôle d'intégrité exécuté à l'import (coût négligeable)."""
    vus: set[str] = set()
    for numero, libelle in PLAN_SYSCOHADA:
        if numero in vus:
            raise AssertionError(f"Compte en double dans le plan : {numero}")
        if not numero.isdigit() or not libelle.strip():
            raise AssertionError(f"Entrée invalide : {numero!r} {libelle!r}")
        if len(numero) > 1 and numero[:-1] not in _INDEX and len(numero) <= 3:
            raise AssertionError(f"Parent manquant pour {numero}")
        vus.add(numero)


_controler_referentiel()
